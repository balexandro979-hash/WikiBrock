                <div class="tarjetaIngredientes">
                    <h3>Ingredientes</h3>
                    <h4>Para el caldo y la carne:</h4>
                     <ul>
                        <li>1 kg de carne de cerdo (pierna o maciza en cubos).</li>
                        <li>1/2 kg de costilla de cerdo en trozos.</li>
                        <li>3 latas (aprox. 1.2 kg) de maíz pozolero precocido, lavado y escurrido.</li>
                        <li>1 cebolla blanca partida en cuartos.</li>
                        <li>8 dientes de ajo.</li>
                        <li>Hojas de laurel y sal al gusto.</li>
                    </ul>
                    <h4>Para el adobo (Salsa):</h4>
                     <ul>
                        <li>5 chiles anchos y 5 chiles guajillos (sin semillas ni venas).</li>
                        <li>6 dientes de ajo y 1/2 cebolla picada.</li>
                        <li>1 cucharadita de orégano, 1 de comino y 1 de pimienta.</li>
                        <li>2 cucharadas de aceite vegetal.</li>
                    </ul>
                    <h4>Para la guarnición:</h4>
                     <ul>
                        <li>Lechuga finamente picada.</li>
                        <li>Rábanos en rodajas delgadas.</li>
                        <li>Cebolla blanca picada.</li>
                        <li>Limones, orégano seco y chile piquín.</li>
                        <li>Tostadas y aguacate en cubos.</li>
                    </ul>
                </div>

                <div class="tarjetaSustituciones">
                     <h3>Sustituciones 🔄</h3>
                       <p>¿Sin costilla? Usa solo pierna o lomo para una versión con menos grasa.</p> 
                       <p>¿Poco tiempo? Puedes cocer la carne en una olla de presión para reducir el tiempo a la mitad.</p>
                       <p>¿Prefieres pollo? Sustituye el cerdo por pechuga y muslos, el caldo quedará igual de delicioso.</p>

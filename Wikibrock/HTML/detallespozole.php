            <section class="columnaDerecha">
                <ol class="pasosPreparacion">
                    <h2>Preparación:</h2>
                    <br>
                    <li>
                    <h3>Preparación y limpieza del caldo base</h3>
                    <p>En una olla grande y profunda, vierte los 4 litros de agua y llévala a ebullición. Agrega la carne de cerdo cortada en cubos, las costillas, la cebolla blanca cortada en cuartos, los 8 dientes de ajo pelados, las hojas de laurel y una buena pizca de sal. Es importante que el agua cubra perfectamente la carne.</p>
                    </li>
                    <li>
                    <h3>Cocción lenta de la carne</h3>
                    <p>Una vez que el agua vuelva a hervir, reduce el fuego a medio-bajo. Durante la primera media hora, notarás que se forma una capa de espuma y grasa en la superficie; retírala constantemente con una espumadera o un cucharón para lograr un caldo limpio y sin impurezas. Tapa parcialmente la olla y deja cocinar por aproximadamente 2 horas o hasta que la carne esté tan suave que se desprenda del hueso. Si el agua se reduce mucho, agrega un poco de agua caliente para mantener el nivel.</p>
                    </li>
                    <li>
                    <h3>3. Limpieza y rehidratación de los chiles</h3>
                    <p>Mientras la carne se cocina, toma los chiles anchos y guajillos. Ábrelos con cuidado para retirarles el tallo, las semillas y las venas. Pon a calentar agua en una olla pequeña y, cuando rompa el hervor, apaga el fuego y sumerge los chiles. Déjalos reposar tapados unos 25 minutos para que se ablanden por completo.</p>
                    </li>
                    <li>
                    <h3>Licuado del adobo</h3>
                    <p>Escurre los chiles (puedes reservar un poco de esa agua) y pásalos a la licuadora. Añade los 6 dientes de ajo restantes, la media cebolla picada, el orégano, el comino y la pimienta. Licúa a velocidad alta, agregando chorritos del agua de remojo o un poco de caldo de la carne para facilitar el proceso, hasta obtener una salsa de textura muy suave.</p>
                    </li>
                    <li>
                    <h3>Sofreír la salsa para potenciar el sabor</h3>
                    <p>En una sartén amplia, calienta las 2 cucharadas de aceite a fuego medio. Con precaución (porque tiende a salpicar), vierte la salsa licuada. Sazona con un poco de sal, reduce la flama y deja que hierva a fuego lento por unos 25 minutos, moviendo ocasionalmente. Verás cómo el color se oscurece y los sabores se concentran.</p>
                    </li>
                    <li>
                    <h3>Limpieza final del caldo</h3>
                    <p>Regresa tu atención a la olla principal. Cuando la carne esté lista, retira del caldo los trozos de cebolla, los ajos enteros y las hojas de laurel y deséchalos. Puedes sacar momentáneamente las costillas para quitarles los huesos si prefieres servir solo la carne limpia.</p>
                    </li>
                    <li>
                    <h3>Fusión y toque final con el maíz</h3>
                    <p>Pasa el adobo frito por un colador metálico dejándolo caer directamente sobre el caldo limpio. Revuelve bien para que el líquido tome ese rojo vibrante. En cuanto suelte de nuevo el hervor, incorpora las 3 latas de maíz pozolero. Baja el fuego y deja cocinar todo junto por unos 15 a 20 minutos más. Esto permitirá que el maíz absorba la sazón del adobo. Prueba de sal y ajusta si es necesario.</p>
                    </li>
                    <li>
                    <h3>Emplatado y guarniciones</h3>
                    <p>Sirve el pozole bien caliente en platos pozoleros hondos. Al centro de la mesa, coloca tazones con la lechuga picada, los rábanos en rodajas, la cebolla picada, mitades de limón, chile piquín y orégano seco. Deja que cada quien personalice su plato a su gusto y acompáñalo con unas buenas tostadas.</p>
                    </li> 
                </ol>


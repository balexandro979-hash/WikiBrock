            <section class="columnaDerecha">
                <ol class="pasosPreparacion">
                    <h2>Preparación:</h2>
                    <br>
                    <li>
                        <h3>Arma la base de la salsa</h3>
                        <p>Lleva a una ollita los tomatillos, los chiles serranos y el diente de ajo. Cúbrelos con agua y déjalos hervir a fuego lento por unos 12 o 15 minutos. Sabrás que están listos cuando cambien de color y se sientan suaves. ¡Ojo! No dejes que se rompan los tomatillos para que no se amargue la salsa.</p>
                    </li>
                    <li>
                        <h3>Licúa con truco</h3>
                        <p>Escurre los ingredientes pero guarda 1/4 de taza del agua de la cocción. Pásalo todo a la licuadora con el diente de ajo. Dale marcha hasta lograr una textura tersa y uniforme. Si sientes que quedó muy espesa, añade un chorrito del agua que reservaste.</p>
                    </li>
                    <li>
                        <h3>El secreto del totopo perfecto</h3>
                        <p>Calienta las primeras cucharadas de aceite en una sartén amplia. Fríe los triángulos de tortilla en tandas pequeñas para que no se encimen y queden bien doraditos y crujientes. Conforme salgan, escúrrelos en papel absorbente. (Tip de abuela: Si dejas las tortillas secando al aire desde la noche anterior, absorben menos grasa y quedan de campeonato).</p>
                    </li>
                    <li>
                        <h3>Sazona y espese de la salsa</h3>
                        <p>Limpia la sartén con una toalla de papel para quitar residuos quemados, pon fuego medio y añade dos cucharaditas de aceite limpio. Vierte la salsa verde con cuidado, sazona con sal al gusto y déjala sazonar por 5 minutos para que agarre cuerpo y sabor.</p>
                    </li> 
                    <li>
                        <h3>El baño de gloria</h3>
                        <p>Agrega el pollo deshebrado y las tortillas crujientes a la sartén de manera envolvente para que se empapen por completo sin romperse. Cocina todo junto por un par de minutos para que el totopo absorba el adobo pero mantenga su textura firme.</p>
                    </li> 
                    <li>
                        <h3>Emplata con orgullo</h3>
                        <p>Sirve de inmediato en un plato hondo. Corona generosamente con hilos de crema, una lluvia de queso fresco, los aros de cebolla y el cilantro picado. Si tienes frijolitos refritos a la mano o un buen aguacate, ya coronaste el día.</p>
                    </li> 
                </ol>

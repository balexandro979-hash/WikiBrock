                    <h4>Para la Salsa Verde Callejera:</h4>
                     <ul>
                        <li>1/2 kg de tomatillos verdes (sin cáscara y bien lavados).</li>
                        <li>2 a 3 chiles serranos (dependiendo qué tanto aguante le tengas al picante).</li>
                        <li>1 diente de ajo grande.</li>
                        <li>Sal al gusto.</li>
                    </ul>
                    <h4>Para el Armado de la Obra de Arte:</h4>
                    <ul>
                        <li>12 tortillas de maíz (de preferencia del día anterior, cortadas en 6 u 8 triángulos).</li>
                        <li>1 1/2 tazas de pechuga de pollo (ya cocida y bien deshebrada).</li>
                        <li>1/3 de taza de aceite vegetal (para lograr ese dorado perfecto).</li>
                    </ul>
                    <h4>Para Decorar y Darle Sabor:</h4>
                    <ul>
                        <li>1/2 taza de crema fresca.</li>
                        <li>1/2 taza de queso fresco desmenuzado (o cotija para más intensidad).</li>
                        <li>1/3 de taza de cilantro fresco finamente picado.</li>
                        <li>2 rodajas de cebolla blanca (separadas en aros).</li>
                    </ul>

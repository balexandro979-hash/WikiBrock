            <section class="columnaDerecha">
                <ol class="pasosPreparacion">
                    <h2>Preparación:</h2>
                    <br>
                     <li>
                    <h3>Prepara el adobo</h3>
                    <p>Coloca los chiles en agua caliente durante unos 15 minutos para que se suavicen. Después licúalos junto con el vinagre, el jugo de piña, el achiote, el ajo, la cebolla, el orégano, el comino, la sal y la pimienta hasta obtener una mezcla uniforme.</p>
                    </li>
                    <li>
                    <h3>Marina la carne</h3>
                    <p>Cubre completamente la carne con el adobo y déjala reposar en el refrigerador por al menos 2 horas., para un sabor más intenso se recomienda dejarla toda la noche.</p>
                    </li>
                    <li>
                    <h3>Cocina los ingredientes</h3>
                    <p>Asa la carne en una plancha o sartén caliente hasta que esté bien cocida y ligeramente dorada, al mismo tiempo, cocina la piña hasta que caramelice un poco.</p>
                    </li>
                    <li>
                    <h3>Pica y prepara</h3>
                    <p>Corta la carne y la piña en trozos pequeños. Calienta las tortillas de maíz.</p>
                    </li> <li>
                    <h3>Arma los tacos</h3>
                    <p>Coloca la carne sobre las tortillas y agrega piña, cebolla, cilantro y salsa al gusto. Acompaña con unas gotas de limón.</p>
                    </li> 
                </ol>

